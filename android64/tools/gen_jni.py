#!/usr/bin/env python3
"""Generate the exported Java_* wrappers of the 64-bit libgame.so from the smali native methods.

    python android64/tools/gen_jni.py <android dir> <out.c>

Reads android/smali*/**/*.smali (read-only). For every `.method ... native name(sig)ret` it emits
a host JNI function with the real 64-bit signature that converts its arguments to guest words
(AAPCS soft-float: 64-bit values in an even register pair or 8-aligned stack slot, float as bits,
objects as guest local handles) and calls the translated guest export of the same name through
jni_bridge.c (big stack, local-ref frame, pin sync).
"""
import re
import sys
from pathlib import Path

CTYPE = {"Z": "jboolean", "B": "jbyte", "C": "jchar", "S": "jshort", "I": "jint", "J": "jlong",
         "F": "jfloat", "D": "jdouble", "L": "jobject", "V": "void"}


def mangle(s):
    out = []
    for ch in s:
        if ch == "/":
            out.append("_")
        elif ch == "_":
            out.append("_1")
        elif ch == ";":
            out.append("_2")
        elif ch == "[":
            out.append("_3")
        elif ch.isalnum() and ord(ch) < 128:
            out.append(ch)
        else:
            out.append(f"_0{ord(ch):04x}")
    return "".join(out)


def parse_sig(sig):
    m = re.fullmatch(r"\((.*)\)(.+)", sig)
    args, ret, p = [], m[2], m[1]
    i = 0
    while i < len(p):
        t = p[i]
        while p[i] == "[":
            i += 1
        if p[i] == "L":
            i = p.index(";", i)
        i += 1
        args.append("L" if t in "L[" else t)
    return args, "L" if ret[0] in "L[" else ret[0]


def natives(android):
    seen = {}
    for f in sorted(android.glob("smali*/**/*.smali")):
        cls = None
        for line in f.read_text(encoding="utf-8", errors="replace").splitlines():
            if line.startswith(".class "):
                cls = re.search(r"L([^;]+);", line)[1]
            m = re.match(r"\.method\s+(.*?)\s*([\w$<>]+)(\(.*)$", line)
            if m and re.search(r"\bnative\b", m[1]):
                name, sig = m[2], m[3]
                key = f"Java_{mangle(cls)}_{mangle(name)}"
                if key in seen:
                    sys.exit(f"overloaded native {cls}.{name}: long JNI names not supported")
                seen[key] = (cls, name, sig, "static" in m[1].split())
    return seen


def emit(items):
    out = ["/* Generated by android64/tools/gen_jni.py from the smali native methods. Do not edit. */",
           "#include <jni.h>", "#include <stdint.h>", "#include <string.h>", "",
           "typedef struct { void *t; JNIEnv *saved_env; uint32_t mark; int nframes; } BridgeFrame;",
           "void bridge_begin(BridgeFrame *f, JNIEnv *env);", "void bridge_end(BridgeFrame *f);",
           "uint32_t bridge_in(jobject o);", "jobject bridge_out(uint32_t h);", "uint32_t bridge_guest_env(void);",
           "uint64_t bridge_call(const char *name, uint32_t *addr, int n, const uint32_t *args);", ""]
    for key, (cls, name, sig, static) in sorted(items.items()):
        args, ret = parse_sig(sig)
        params = ["JNIEnv *env", "jclass self" if static else "jobject self"]
        params += [f"{CTYPE[t]} a{i}" for i, t in enumerate(args)]
        body = ["  uint32_t w[32];", "  int n = 0;", "  BridgeFrame f;", "  bridge_begin(&f, env);",
                "  w[n++] = bridge_guest_env();", "  w[n++] = bridge_in(self);"]
        for i, t in enumerate(args):
            if t in "JD":
                body.append("  if (n & 1) w[n++] = 0;")
                body.append(f"  {{ uint64_t u; memcpy(&u, &a{i}, 8); w[n++] = (uint32_t)u; w[n++] = (uint32_t)(u >> 32); }}")
            elif t == "F":
                body.append(f"  memcpy(&w[n++], &a{i}, 4);")
            elif t == "L":
                body.append(f"  w[n++] = bridge_in(a{i});")
            elif t in "BS":
                body.append(f"  w[n++] = (uint32_t)(int32_t)a{i};")
            else:
                body.append(f"  w[n++] = (uint32_t)a{i};")
        body.append("  static uint32_t addr;")
        body.append(f'  uint64_t r = bridge_call("{key}", &addr, n, w);')
        if ret == "V":
            body += ["  (void)r;", "  bridge_end(&f);"]
        elif ret == "L":
            body += ["  jobject o = bridge_out((uint32_t)r);", "  bridge_end(&f);", "  return o;"]
        elif ret in "JD":
            body += [f"  {CTYPE[ret]} v; memcpy(&v, &r, 8);", "  bridge_end(&f);", "  return v;"]
        elif ret == "F":
            body += ["  uint32_t b = (uint32_t)r; jfloat v; memcpy(&v, &b, 4);", "  bridge_end(&f);", "  return v;"]
        else:
            body += [f"  {CTYPE[ret]} v = ({CTYPE[ret]})r;", "  bridge_end(&f);", "  return v;"]
        out.append(f"/* {cls}.{name}{sig}{' static' if static else ''} */")
        out.append(f"JNIEXPORT {CTYPE[ret]} JNICALL {key}({', '.join(params)}) {{")
        out += body
        out.append("}")
        out.append("")
    return "\n".join(out)


def main():
    android, dst = Path(sys.argv[1]), Path(sys.argv[2])
    items = natives(android)
    text = emit(items)
    dst.parent.mkdir(parents=True, exist_ok=True)
    if not dst.exists() or dst.read_text(encoding="utf-8") != text:
        dst.write_text(text, encoding="utf-8")
    print(f"[jni] {len(items)} native methods -> {dst}")


if __name__ == "__main__":
    main()
